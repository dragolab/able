package com.dragolabs.able.feature.tools.hotspot

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import androidx.core.content.ContextCompat
import com.dragolabs.able.core.capability.ShizukuAdapter
import com.dragolabs.able.core.common.AbleError
import com.dragolabs.able.core.common.AbleResult
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.distinctUntilChanged

/** Outcome of a privileged helper command. */
sealed interface HotspotCommandResult {
    /** The system answered; [code] is a TetheringManager.TETHER_ERROR_* value (0 = no error). */
    data class Answered(val code: Int, val output: String) : HotspotCommandResult

    /** The command could not be delivered or the API is missing; [reason] is technical detail. */
    data class Failed(val reason: String) : HotspotCommandResult
}

/**
 * Hotspot status and control (HOT-001).
 *
 * Android has no public API for third-party apps to change tethering or the soft-AP
 * configuration. Status for everyone comes from the system's sticky soft-AP state broadcast (or
 * UNKNOWN if a device does not send it). With Shizuku, Able runs [HotspotShellMain] as the shell
 * user to start/stop tethering, read and write the configuration, and list clients; every change
 * is read back by the caller.
 */
class HotspotDataSource(private val context: Context, private val shizuku: ShizukuAdapter) {

    fun readState(): HotspotState = runCatching {
        val sticky = ContextCompat.registerReceiver(context, null, IntentFilter(ACTION_AP_STATE), ContextCompat.RECEIVER_EXPORTED)
        sticky?.let { HotspotState.fromApState(it.getIntExtra(EXTRA_AP_STATE, -1)) } ?: HotspotState.UNKNOWN
    }.getOrDefault(HotspotState.UNKNOWN)

    fun observeState(): Flow<HotspotState> = callbackFlow {
        trySend(readState())
        val receiver = object : BroadcastReceiver() {
            override fun onReceive(context: Context, intent: Intent) {
                trySend(HotspotState.fromApState(intent.getIntExtra(EXTRA_AP_STATE, -1)))
            }
        }
        val registered = runCatching {
            ContextCompat.registerReceiver(context, receiver, IntentFilter(ACTION_AP_STATE), ContextCompat.RECEIVER_EXPORTED)
        }.isSuccess
        awaitClose { if (registered) runCatching { context.unregisterReceiver(receiver) } }
    }.distinctUntilChanged()

    val isShizukuReady: Boolean get() = shizuku.isReady()

    /** State, configuration, capabilities and clients in one helper run. */
    suspend fun snapshot(): AbleResult<HotspotSnapshot> = when (val result = run("info", timeoutMs = 15_000)) {
        is AbleResult.Success -> AbleResult.Success(HotspotWire.parse(result.data))
        is AbleResult.Failure -> result
        AbleResult.Loading -> AbleResult.Loading
    }

    /** Authoritative state through the helper; falls back to the broadcast state. */
    suspend fun readPrivilegedState(): HotspotState {
        val result = run("state", timeoutMs = 8_000)
        val state = (result as? AbleResult.Success)?.let { HotspotWire.parse(it.data).state }
        return state?.takeIf { it != HotspotState.UNKNOWN } ?: readState()
    }

    suspend fun start(): HotspotCommandResult = command("start")

    suspend fun stop(): HotspotCommandResult = command("stop")

    /** Applies [edit]; the answer's output contains the read-back configuration. */
    suspend fun apply(edit: HotspotEdit): HotspotCommandResult = command("set", *HotspotWire.editArgs(edit).toTypedArray())

    private suspend fun command(vararg args: String): HotspotCommandResult = when (val result = run(*args, timeoutMs = 20_000)) {
        is AbleResult.Success -> {
            val code = HotspotWire.parseResult(result.data)
            if (code != null) {
                HotspotCommandResult.Answered(code, result.data)
            } else {
                HotspotCommandResult.Failed(HotspotWire.parseErrors(result.data).joinToString("; ").ifEmpty { "no answer" })
            }
        }
        is AbleResult.Failure -> HotspotCommandResult.Failed(result.error.message)
        AbleResult.Loading -> HotspotCommandResult.Failed("busy")
    }

    private suspend fun run(vararg args: String, timeoutMs: Long): AbleResult<String> {
        val apk = context.applicationInfo.sourceDir
        if (apk.isNullOrEmpty() || apk.contains('\'')) return AbleResult.Failure(AbleError.Unknown("APK path unavailable"))
        // Arguments are generated by HotspotWire (hex, digits, MAC addresses): nothing to quote.
        val command = "CLASSPATH='$apk' /system/bin/app_process /system/bin --nice-name=able_hotspot " +
            "${HotspotShellMain::class.java.name} ${args.joinToString(" ")}"
        return shizuku.executeCommand(command, timeoutMs)
    }

    private companion object {
        // WifiManager's soft-AP state broadcast (system API, stable since API 26).
        const val ACTION_AP_STATE = "android.net.wifi.WIFI_AP_STATE_CHANGED"
        const val EXTRA_AP_STATE = "wifi_state"
    }
}
